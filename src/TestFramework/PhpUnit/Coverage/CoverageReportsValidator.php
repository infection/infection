declare(strict_types=1);

namespace Infection\TestFramework\PhpUnit\Coverage;

use function count;
use function implode;
use Infection\TestFramework\Coverage\CoverageNotFound;
use Infection\TestFramework\Coverage\Locator\ReportLocator;
use Infection\TestFramework\Coverage\Locator\Throwable\ReportLocationThrowable;
use const PHP_EOL;
use function sprintf;

/** @internal */
final readonly class CoverageReportsValidator
{
    public function __construct(
        private string $coveragePath,
        private ReportLocator $jUnitReportLocator,
        private ReportLocator $indexXmlCoverageLocator,
    ) {
    }

    public function checkExists(): void
    {
        try {
            $this->indexXmlCoverageLocator->locate();
        } catch (ReportLocationThrowable $exception) {
            throw new CoverageNotFound(sprintf(
                'Could not find the "index.xml" file. Please ensure that the XML coverage report has been properly generated at the right place. The PHPUnit option for the path given is "--coverage-xml=%s/coverage-xml"',
                $this->coveragePath,
            ), 0, $exception);
        }

        try {
            $this->jUnitReportLocator->locate();
        } catch (ReportLocationThrowable $exception) {
            throw new CoverageNotFound(sprintf(
                'Could not find the JUnit file report. Please ensure that the JUnit coverage report has been properly generated at the right place. The PHPUnit option for the path given is "--log-junit=%s/junit.xml"',
                $this->coveragePath,
            ), 0, $exception);
        }
    }

    public function checkGenerated(string $commandLine, string $output): void
    {
        $errors = [];

        try {
            $this->indexXmlCoverageLocator->locate();
        } catch (ReportLocationThrowable $exception) {
            $errors[] = sprintf('- The file "index.xml" could not be found: %s', $exception->getMessage());
        }

        try {
            $this->jUnitReportLocator->locate();
        } catch (ReportLocationThrowable $exception) {
            $errors[] = sprintf('- The JUnit file could not be found: %s', $exception->getMessage());
        }

        if (count($errors) === 0) {
            return;
        }

        throw new CoverageNotFound(sprintf(<<<TXT
            The code coverage generated by the initial test run is invalid. Please report the issue on the
            infection repository "https://github.com/infection/infection".

            ```
            $ %s
            %s
            ```

            Issue(s):
            %s
            TXT,
            $commandLine,
            $output,
            implode(PHP_EOL, $errors),
        ));
    }
}
